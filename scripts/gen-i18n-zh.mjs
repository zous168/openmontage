// 读取现有 zh.ts,追加缺失键
let zh = fs.readFileSync(ZH_PATH, 'utf-8');
const existing = new Set([...zh.matchAll(/^\s*"([^"]+)":/gm)].map((m) => m[1]));
const missing = Object.entries(M).filter(([k]) => !existing.has(k));
if (missing.length === 0) {
  console.log('zh.ts 已全部覆盖,无需更新');
  process.exit(0);
}
// 在导出前插入(定位 export const zh 行)
const lines = zh.split('\n');
const insertAt = lines.findIndex((l) => l.includes('export const zh'));
const block = missing
  .map(([k, v]) => `  "${k}": "${v}",`)
  .join('\n');
lines.splice(insertAt, 0, `// ---- 批量抽离的 UI 文案(原文即键) ----\n${block}`);
fs.writeFileSync(ZH_PATH, lines.join('\n'), 'utf-8');
console.log(`zh.ts 新增 ${missing.length} 条中文映射`);
